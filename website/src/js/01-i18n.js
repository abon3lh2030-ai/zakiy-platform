function t(key, vars) {
  let str = (I18N[currentLang] && I18N[currentLang][key]) || I18N.ar[key] || key;
  if (vars) {
    Object.keys(vars).forEach(k => { str = str.split(`{${k}}`).join(vars[k]); });
  }
  return str;
}

function updateLangButtonsActiveState() {
  const arBtn = document.getElementById('langArBtn');
  const enBtn = document.getElementById('langEnBtn');
  if (arBtn) arBtn.classList.toggle('active', currentLang === 'ar');
  if (enBtn) enBtn.classList.toggle('active', currentLang === 'en');
}

// تُستدعى أول تحميل الصفحة، وكل مرة يبدّل المستخدم اللغة - تعيد ترجمة كل
// عنصر ثابت معلّم بـ data-i18n/data-i18n-ph، وتحدّث اتجاه/عنوان الصفحة
function applyLanguage() {
  document.documentElement.setAttribute('lang', currentLang);
  document.documentElement.setAttribute('dir', currentLang === 'ar' ? 'rtl' : 'ltr');
  document.title = t('page_title');
  document.querySelectorAll('[data-i18n]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-ph')); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
  updateLangButtonsActiveState();
  if (typeof updateDarkModeButtonLabel === 'function') updateDarkModeButtonLabel();
}

document.querySelectorAll('.lang-choice-btn').forEach(btn => {
  btn.addEventListener('click', () => {
    currentLang = btn.dataset.lang;
    localStorage.setItem('zakiy-lang', currentLang);
    applyLanguage();
    if (currentAccessToken) {
      supabaseClient.auth.updateUser({ data: { language: currentLang } }).catch(() => {});
    }
  });
});

applyLanguage();

function show(id) {
  document.getElementById(id).classList.remove('hidden');
  if (id === 'sidebar') document.body.classList.add('with-sidebar');
}
function hide(id) {
  document.getElementById(id).classList.add('hidden');
  if (id === 'sidebar') document.body.classList.remove('with-sidebar');
}

